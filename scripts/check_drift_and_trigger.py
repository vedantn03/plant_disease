"""
scripts/check_drift_and_trigger.py
==================================
Closed-loop drift monitoring and retraining trigger.
Reads reports/drift_report.json (or metrics generated by simulate_drift.py),
evaluates statistical drift thresholds (Kolmogorov-Smirnov p < 0.05, PSI > 0.25),
and if drift is detected, issues a structured retraining trigger artifact.

Usage:
  python scripts/check_drift_and_trigger.py
"""

import json
from pathlib import Path
import sys

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from src.utils import get_logger

log = get_logger("drift_trigger")


def main():
    drift_json_path = PROJECT_ROOT / "reports" / "drift_metrics.json"
    
    # If drift metrics json does not exist, run simulate_drift logic to create one
    if not drift_json_path.exists():
        log.info("No existing drift metrics file found; generating drift assessment...")
        import numpy as np
        from scipy import stats
        
        # Simulate baseline vs drifted distribution comparison
        rng = np.random.default_rng(42)
        ref_blur = rng.normal(120.0, 25.0, 100)
        drift_blur = rng.normal(45.0, 15.0, 100)  # Heavy lens blur
        
        ref_bright = rng.normal(135.0, 20.0, 100)
        drift_bright = rng.normal(90.0, 18.0, 100)  # Darker lighting
        
        ks_blur = stats.ks_2samp(ref_blur, drift_blur)
        ks_bright = stats.ks_2samp(ref_bright, drift_bright)
        
        drift_metrics = {
            "blur": {
                "ks_statistic": round(float(ks_blur.statistic), 4),
                "p_value": float(ks_blur.pvalue),
                "psi": 0.8420,
                "drift_detected": bool(ks_blur.pvalue < 0.05)
            },
            "brightness": {
                "ks_statistic": round(float(ks_bright.statistic), 4),
                "p_value": float(ks_bright.pvalue),
                "psi": 0.6150,
                "drift_detected": bool(ks_bright.pvalue < 0.05)
            }
        }
        with open(drift_json_path, "w", encoding="utf-8") as f:
            json.dump(drift_metrics, f, indent=2)
    else:
        with open(drift_json_path, "r", encoding="utf-8") as f:
            drift_metrics = json.load(f)

    # Evaluate drift thresholds
    reasons = []
    drift_triggered = False

    for feature, m in drift_metrics.items():
        psi = m.get("psi", 0.0)
        p_val = m.get("p_value", 1.0)
        if psi > 0.25 or p_val < 0.05:
            drift_triggered = True
            reasons.append(f"{feature.capitalize()} drift: PSI={psi:.4f} (threshold > 0.25), KS p-value={p_val:.2e} (< 0.05)")

    trigger_payload = {
        "drift_detected": drift_triggered,
        "action_required": "TRIGGER_CLOSED_LOOP_RETRAINING" if drift_triggered else "MONITORING_STEADY_STATE",
        "timestamp": Path(__file__).stat().st_mtime,
        "violations": reasons,
        "recommended_command": "make retrain" if drift_triggered else None,
        "notes": (
            "Simulated field-data optical degradation triggered automated retraining request. "
            "Downstream pipeline will version newly arrived data, audit splits, retrain, and evaluate at gate."
        ) if drift_triggered else "Data distributions within nominal tolerances."
    }

    out_path = PROJECT_ROOT / "reports" / "retraining_trigger.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(trigger_payload, f, indent=2)

    log.info(f"Drift Analysis Status: {trigger_payload['action_required']}")
    for r in reasons:
        log.warning(f"  Violation: {r}")
    log.info(f"Retraining trigger log saved to {out_path}")
    print(json.dumps(trigger_payload, indent=2))


if __name__ == "__main__":
    main()
